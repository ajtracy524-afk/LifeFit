export function getProgram(id: string): WorkoutProgram | undefined {
  return PROGRAMS.find((p) => p.id === id) ?? personalProgram(id);
}

export function findTemplate(templateId: string): WorkoutTemplate | undefined {
  for (const program of PROGRAMS) {
    const template = program.templates.find((t) => t.id === templateId);
    if (template) return template;
  }
  return EXTRA_TEMPLATES.find((t) => t.id === templateId) ?? personalRoutine(templateId);
}

/** Every built-in session once (programs share sessions, e.g. full body in "+ Ausdauer"). */
export function builtInTemplates(): WorkoutTemplate[] {
  const seen = new Map<string, WorkoutTemplate>();
  for (const t of [...PROGRAMS.flatMap((p) => p.templates), ...EXTRA_TEMPLATES]) if (!seen.has(t.id)) seen.set(t.id, t);
  return [...seen.values()];
}

